"""End-to-End Page Photo to LaTeX (.tex) Pipeline.

Processes a full page photo:
1. Deskews tilt and cleans lighting/shadows using OpenCV adaptive thresholding.
2. Segments page into individual equation lines using horizontal projection profile.
3. Runs the custom-trained Img2Latex model (with beam search) on each line.
4. Checks LaTeX compilation syntax for each line.
5. Emits a clean, compilable .tex file inside an amsmath / align* template.
"""

import argparse
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple, Union

import cv2
import numpy as np

from src.pipeline.preprocess import preprocess_page
from src.pipeline.split_lines import split_page_into_lines, LineCrop
from src.model.infer import LatexPredictor
from src.model.evaluate import check_latex_compilable


DEFAULT_TEX_TEMPLATE = r"""\documentclass{article}
\usepackage{amsmath,amssymb}
\usepackage[margin=1in]{geometry}

\begin{document}

% ==========================================
% Generated by Math2LaTeX
% Notes processed from photo
% ==========================================

\begin{align*}
{equations}
\end{align*}

\end{document}
"""


def format_latex_document(line_results: List[Dict[str, Any]]) -> str:
    """Format individual predicted lines into a full compilable LaTeX document."""
    equation_lines: List[str] = []

    for item in line_results:
        idx = item["index"] + 1
        latex = item["latex"]
        conf = item["confidence"]
        compiles = item["compiles"]

        comment = f"  % Line {idx} (Confidence: {conf:.1%})"
        if not compiles:
            comment += " - [WARNING: Syntax/compile issue detected on this line - please verify]"

        # Add LaTeX equation line with align* line terminator \\
        eq_line = f"  {latex} \\\\"
        equation_lines.append(f"{comment}\n{eq_line}")

    equations_str = "\n".join(equation_lines)
    return DEFAULT_TEX_TEMPLATE.replace("{equations}", equations_str)


class PageToTexPipeline:
    """Orchestrates photo deskewing, line segmentation, and LaTeX generation."""

    def __init__(
        self,
        checkpoint_path: str = "checkpoints/best_model.pt",
        config_path: str = "configs/base.yaml",
        device: Optional[str] = None,
    ):
        self.predictor = LatexPredictor(
            checkpoint_path=checkpoint_path,
            config_path=config_path,
            device=device,
        )

    def process_page(
        self,
        image_input: Union[str, Path, np.ndarray],
        output_tex_path: Optional[Union[str, Path]] = None,
        beam_size: int = 4,
    ) -> Tuple[str, List[Dict[str, Any]], List[LineCrop]]:
        """Process a full page photo into LaTeX.
        
        Args:
            image_input: Image filepath or BGR numpy array.
            output_tex_path: Optional path to save resulting .tex file.
            beam_size: Beam search width for line decoding.
            
        Returns:
            tex_content: Complete LaTeX source document string.
            line_details: List of dicts with index, latex, confidence, compiles, bbox.
            line_crops: List of LineCrop objects.
        """
        if isinstance(image_input, (str, Path)):
            img = cv2.imread(str(image_input))
            if img is None:
                raise FileNotFoundError(f"Could not read image from {image_input}")
        else:
            img = image_input

        # 1. Clean and straighten page
        straight_rgb, binary_inv, cleaned_gray = preprocess_page(img)

        # 2. Split into equation lines
        line_crops = split_page_into_lines(cleaned_gray, binary_inv=binary_inv)
        print(f"Detected {len(line_crops)} equation lines on the page.")

        line_details: List[Dict[str, Any]] = []

        # 3. Predict LaTeX for each cropped line
        for crop in line_crops:
            latex_str, conf = self.predictor.predict(crop.image, beam_size=beam_size)
            compiles = check_latex_compilable(latex_str)

            line_details.append({
                "index": crop.index,
                "latex": latex_str,
                "confidence": conf,
                "compiles": compiles,
                "bbox": crop.bbox,
            })
            print(f"Line {crop.index + 1}: {latex_str} (Conf: {conf:.1%}, Compiles: {compiles})")

        # 4. Assemble into full .tex document
        tex_content = format_latex_document(line_details)

        # 5. Save to disk if path is provided
        if output_tex_path:
            out_p = Path(output_tex_path)
            out_p.parent.mkdir(parents=True, exist_ok=True)
            out_p.write_text(tex_content, encoding="utf-8")
            print(f"Saved LaTeX document to {out_p.resolve()}")

        return tex_content, line_details, line_crops


def main():
    parser = argparse.ArgumentParser(description="Convert full page handwritten math photo to LaTeX")
    parser.add_argument("photo", help="Path to input page photo")
    parser.add_argument("-o", "--output", default="notes.tex", help="Output .tex filename")
    parser.add_argument("--checkpoint", default="checkpoints/best_model.pt", help="Model checkpoint")
    parser.add_argument("--config", default="configs/base.yaml", help="Configuration file")
    parser.add_argument("--beam_size", type=int, default=4, help="Beam search width")
    args = parser.parse_args()

    pipeline = PageToTexPipeline(checkpoint_path=args.checkpoint, config_path=args.config)
    pipeline.process_page(args.photo, output_tex_path=args.output, beam_size=args.beam_size)


if __name__ == "__main__":
    main()
